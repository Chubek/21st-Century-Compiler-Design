class Converter:
    def __init__(self):
        self.warnings: set[str] = set()

    def plain(self, source: str) -> str:
        text = without_comments(source)

        def convert(text: str) -> str:
            out = []
            pos = 0

            def arg() -> str:
                nonlocal pos
                value, pos = group(text, pos)
                return convert(value)

            while pos < len(text):
                char = text[pos]
                if char == "\\":
                    match = COMMAND.match(text, pos)
                    if not match:
                        out.append(char)
                        pos += 1
                        continue
                    name = match[1]
                    pos = match.end()
                    if name in {"verb", "verb*"}:
                        delimiter = text[pos:pos + 1]
                        end = text.find(delimiter, pos + 1) if delimiter else -1
                        if end < 0:
                            raise ExportError("unclosed inline verbatim")
                        out.append(text[pos + 1:end])
                        pos = end + 1
                    elif name in WRAPPERS:
                        out.append(arg())
                    elif name in BRACKETS:
                        out.append(BRACKETS[name] + "[" + arg() + "]")
                    elif name in {"frac", "dfrac", "tfrac"}:
                        numerator, denominator = arg(), arg()
                        out.append("(" + numerator + ")/(" + denominator + ")")
                    elif name == "sqrt":
                        start = pos
                        pos = optional(text, pos)
                        degree = text[start:pos].strip()
                        out.append("root" + degree + "(" + arg() + ")" if degree else "sqrt(" + arg() + ")")
                    elif name in {"set", "phifn", "Tf", "enquote", "Comment"}:
                        value = arg()
                        out.append({"set": "{" + value + "}", "phifn": "phi(" + value + ")",
                                    "Tf": "f_{" + value + "}", "enquote": '"' + value + '"',
                                    "Comment": " // " + value}[name])
                    elif name in {"assignphi", "Call"}:
                        first, second = arg(), arg()
                        out.append(first + " <- phi(" + second + ")" if name == "assignphi"
                                   else first + "(" + second + ")")
                    elif name in {"ref", "eqref", "cite", "pageref"}:
                        out.append(name + "[" + arg() + "]")
                    elif name == "multicolumn":
                        span, alignment, value = arg(), arg(), arg()
                        out.append(value)
                    elif name in {"makecell", "shortstack"}:
                        pos = optional(text, pos)
                        out.append(arg())
                    elif name in {"begin", "end"}:
                        environment = arg()
                        if environment not in MATH_ENVS:
                            raise ExportError(f"unsupported inline environment: {environment}")
                        if name == "end":
                            out.append(")")
                        else:
                            setup = "[" + arg() + "]" if environment in {"array", "alignedat"} else ""
                            out.append(environment + setup + "(")
                    elif name in SYMBOLS:
                        out.append(SYMBOLS[name])
                    elif name in {"{", "}", "&", "%", "_", "#", "$", "|"}:
                        out.append(name)
                    elif name in {",", ";", ":", "!", " "}:
                        out.append(" ")
                    elif name in {"(", ")", "[", "]"}:
                        pass  # Math delimiters, not mathematical content.
                    elif name == "\\":
                        out.append(" / ")  # A grouped cell's explicit line break.
                    else:
                        # Retain the complete unknown command and its balanced
                        # arguments. Do not erase syntax whose meaning is unknown.
                        start = match.start()
                        while True:
                            after = pos
                            while after < len(text) and text[after].isspace():
                                after += 1
                            if text[after:after + 1] not in {"{", "["}:
                                break
                            _, pos = group(text, after, text[after])
                        out.append(text[start:pos])
                        self.warnings.add(f"retained unsupported inline command \\{name}")
                elif char == "{":
                    value, pos = group(text, pos)
                    # Preserve grouping for subscripts and exponents.
                    grouped = convert(value)
                    out.append("{" + grouped + "}" if pos and out and out[-1] in {"_", "^"} else grouped)
                elif char == "$":
                    pos += 1
                else:
                    out.append(" " if char == "~" else char)
                    pos += 1
            return "".join(out)

        value = re.sub(r"\s+", " ", convert(text)).strip()
        value = value.replace("---", "--")
        # ASCII is a portable interchange format; unfamiliar Unicode remains
        # visibly escaped rather than disappearing in a lossy encoding.
        substitutions = {"−": "-", "≤": "<=", "≥": ">=", "→": "->", "←": "<-",
                         "×": "*", "∈": " in ", "∅": "{}", "“": '"', "”": '"',
                         "‘": "'", "’": "'", "–": "-", "—": "--"}
        for old, new in substitutions.items():
            value = value.replace(old, new)
        if not value.isascii():
            self.warnings.add("retained non-ASCII characters as Unicode escapes")
        return value.encode("ascii", "backslashreplace").decode("ascii")

    def pseudocode(self, body: str) -> str:
        clean = without_comments(body)
        controls = {"Require", "Ensure", "State", "Statex", "If", "ElsIf", "Else", "EndIf",
                    "While", "EndWhile", "For", "ForAll", "EndFor", "Loop", "EndLoop",
                    "Repeat", "Until", "Function", "EndFunction", "Procedure", "EndProcedure"}
        # Only top-level commands delimit statements. Macros inside a condition
        # or a grouped cell cannot accidentally split one.
        tokens = []
        depth = 0
        pos = 0
        while pos < len(clean):
            if clean[pos] == "\\":
                match = COMMAND.match(clean, pos)
                if match:
                    if depth == 0 and match[1] in controls:
                        tokens.append(match)
                    pos = match.end()
                    if match[1] in {"verb", "verb*"}:
                        pos = clean.find(clean[pos], pos + 1) + 1
                    continue
            if clean[pos] == "{":
                depth += 1
            elif clean[pos] == "}":
                depth -= 1
                if depth < 0:
                    raise ExportError("unbalanced pseudocode braces")
            pos += 1
        if depth:
            raise ExportError("unbalanced pseudocode braces")
        if not tokens or clean[:tokens[0].start()].strip():
            raise ExportError("unhandled text before pseudocode statements")
        lines = []
        stack: list[str] = []
        opens = {"If": "IF", "While": "WHILE", "For": "FOR", "ForAll": "FORALL",
                 "Loop": "LOOP", "Repeat": "REPEAT", "Function": "FUNCTION", "Procedure": "PROCEDURE"}
        closes = {"EndIf": "IF", "EndWhile": "WHILE", "EndFor": "FOR",
                  "EndLoop": "LOOP", "Until": "REPEAT", "EndFunction": "FUNCTION",
                  "EndProcedure": "PROCEDURE"}
        for index, token in enumerate(tokens):
            name = token[1]
            stop = tokens[index + 1].start() if index + 1 < len(tokens) else len(clean)
            raw = clean[token.end():stop].strip()
            if name in closes or name in {"Else", "ElsIf"}:
                expected = closes.get(name, "IF")
                if not stack or (stack[-1] != expected and not (expected == "FOR" and stack[-1] == "FORALL")):
                    raise ExportError(f"mismatched pseudocode control \\{name}")
                closed = stack.pop()
            if name in {"If", "ElsIf", "While", "For", "ForAll", "Until"}:
                if raw.startswith("{"):
                    condition, end = group(raw, 0)
                else:
                    condition, end = raw, len(raw)
                    self.warnings.add(f"unbraced \\{name} condition read through the next statement")
                tail = self.plain(raw[end:])
                word = {"ElsIf": "ELSE IF", "Until": "UNTIL"}.get(name, name.upper())
                suffix = " THEN" if name in {"If", "ElsIf"} else " DO" if name in {"While", "For", "ForAll"} else ""
                line = word + " " + self.plain(condition) + suffix + (" " + tail if tail else "")
            elif name in {"Function", "Procedure"}:
                fn, end = group(raw, 0)
                args, end = group(raw, end)
                line = name.upper() + " " + self.plain(fn) + "(" + self.plain(args) + ")"
                if raw[end:].strip():
                    line += " " + self.plain(raw[end:])
            elif name in closes:
                line = "END " + ("FOR" if closed == "FORALL" else closed)
                if raw:
                    line += " " + self.plain(raw)
            else:
                prefix = {"State": "", "Statex": "", "Require": "REQUIRE ", "Ensure": "ENSURE "}.get(name, name.upper() + " ")
                line = (prefix + self.plain(raw)).rstrip()
            lines.append("  " * len(stack) + line)
            if name in opens:
                stack.append(opens[name])
            elif name in {"Else", "ElsIf"}:
                stack.append("IF")
        if stack:
            raise ExportError("unclosed pseudocode control: " + stack[-1])
        return "\n".join(lines)


def column_count(spec: str) -> int:
    pos, count = 0, 0
    while pos < len(spec):
        char = spec[pos]
        pos += 1
        if char.isspace() or char == "|":
            continue
        if char in "lcr":
            count += 1
        elif char in "pmb":
            _, pos = group(spec, pos)
            count += 1
        elif char in "@!><":
            _, pos = group(spec, pos)
        elif char == "*":
            repeat, pos = group(spec, pos)
            nested, pos = group(spec, pos)
            if not repeat.isdigit():
                raise ExportError("nonliteral tabular repetition")
            count += int(repeat) * column_count(nested)
        else:
            raise ExportError(f"unsupported tabular column specification: {spec!r}")
    if not count:
        raise ExportError("empty tabular column specification")
    return count


def markdown_cell(text: str) -> str:
    # Entity escaping keeps raw HTML inert. Escape Markdown punctuation even
    # inside code-like text; backslash-escaped pipes remain GFM cell content.
    text = html.escape(text, quote=False)
    return re.sub(r"([\\`*_~\[\]{}|])", r"\\\1", text).replace("\n", " ")


def table_rows(body: str) -> tuple[int, list[list[str]]]:
    text = without_comments(body)
    pos = optional(text, 0)
    spec, pos = group(text, pos)
    columns = column_count(spec)
    rows: list[list[str]] = []
    row: list[str] = []
    cell: list[str] = []
    depth = 0
    env_stack = []
    while pos < len(text):
        char = text[pos]
        if char == "\\":
            match = COMMAND.match(text, pos)
            if match:
                name = match[1]
                if name in {"verb", "verb*"}:
                    end = text.find(text[match.end()], match.end() + 1) + 1
                    cell.append(text[pos:end])
                    pos = end
                    continue
                if name in {"begin", "end"}:
                    environment, end = group(text, match.end())
                    if environment not in MATH_ENVS:
                        raise ExportError(f"unsupported table cell environment: {environment}")
                    if name == "begin":
                        env_stack.append(environment)
                    elif not env_stack or env_stack.pop() != environment:
                        raise ExportError("mismatched table math environment")
                    cell.append(text[pos:end])
                    pos = end
                    continue
                if depth == 0 and not env_stack and name in {"toprule", "midrule", "bottomrule", "hline", "addlinespace"}:
                    pos = optional(text, match.end())
                    continue
                if depth == 0 and not env_stack and name in {"cmidrule", "cline"}:
                    pos = optional(text, match.end())
                    if text[pos:pos + 1] == "(":
                        close = text.find(")", pos)
                        if close < 0:
                            raise ExportError("unclosed cmidrule trim")
                        pos = close + 1
                    _, pos = group(text, pos)
                    continue
                if depth == 0 and not env_stack and name in {"\\", "tabularnewline"}:
                    row.append("".join(cell).strip())
                    rows.append(row)
                    row, cell = [], []
                    pos = match.end()
                    if text[pos:pos + 1] == "*":
                        pos += 1
                    pos = optional(text, pos)
                    continue
                cell.append(match[0])
                pos = match.end()
                continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth < 0:
                raise ExportError("unbalanced tabular cell")
        if depth == 0 and not env_stack and char == "&":
            row.append("".join(cell).strip())
            cell = []
        else:
            cell.append(char)
        pos += 1
    if depth or env_stack:
        raise ExportError("unbalanced tabular cell")
    if row or "".join(cell).strip():
        rows.append(row + ["".join(cell).strip()])
    if not rows:
        raise ExportError("empty table")
    expanded = []
    for row in rows:
        cells = []
        for cell in row:
            span = 1
            if cell.startswith("\\multicolumn"):
                value, end = group(cell, len("\\multicolumn"))
                if not value.isdigit() or int(value) < 1:
                    raise ExportError("nonliteral or invalid multicolumn span")
                span = int(value)
            cells.extend([cell] + [""] * (span - 1))
        if len(cells) != columns:
            raise ExportError(f"table row has {len(cells)} columns; expected {columns}: {row!r}")
        expanded.append(cells)
    return columns, expanded


def comment_lines(text: str, prefix: str) -> str:
    return "\n".join(prefix + line for line in text.split("\n"))


def fenced(text: str) -> str:
    fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", text)), default=3))
    return fence + "latex\n" + text + "\n" + fence


def inspect_float_shell(text: str, converter: Converter) -> None:
    """Account for material outside the exported body instead of dropping it."""
    text = mask(text)
    pos = optional(text, 0)  # Float placement, if any.
    leftovers = []
    no_args = {"centering", "raggedright", "small", "footnotesize", "scriptsize",
               "tiny", "normalsize", "large", "Large", "noindent"}
    while pos < len(text):
        if text[pos].isspace() or text[pos] in "{}":
            pos += 1
            continue
        match = COMMAND.match(text, pos)
        if match and match[1] in no_args:
            pos = match.end()
        elif match and match[1] in {"caption", "label"}:
            _, pos = group(text, optional(text, match.end()))
        elif match and match[1] in {"begin", "end"}:
            name, end = group(text, match.end())
            if name not in {"center", "minipage"}:
                raise ExportError(f"unsupported float wrapper environment: {name}")
            pos = end
            if name == "minipage" and match[1] == "begin":
                pos = optional(text, pos)
                _, pos = group(text, pos)
        else:
            leftovers.append(text[pos])
            pos += 1
    if leftovers:
        summary = re.sub(r"\s+", " ", "".join(leftovers)).strip()
        converter.warnings.add("unhandled float wrapper/content retained in original LaTeX: " + summary[:120])


@dataclass
class Artifact:
    directory: str
    filename: str
    label: str
    source: str
    caption: str
    content: str


def collect(manuscript: Manuscript) -> tuple[list[Artifact], list[str]]:
    envs = environments(manuscript.text)
    artifacts: list[Artifact] = []
    labels: set[str] = set()
    warnings: list[str] = []
    for child in envs:
        if child.name not in {"pseudocode", "tikzpicture"}:
            continue
        parent = child.parent
        wanted = "algorithm" if child.name == "pseudocode" else "figure"
        while parent and parent.name.removesuffix("*") != wanted:
            parent = parent.parent
        if parent is None:
            raise ExportError(f"{manuscript.source(child.start)}: {child.name} outside a named {wanted}")
    for env in envs:
        kind = env.name.removesuffix("*")
        if kind not in KINDS:
            continue
        source = manuscript.source(env.start)
        prefix, directory, extension, child_name = KINDS[kind]
        raw = manuscript.text[env.body:env.stop]
        captions = arguments(raw, "caption")
        names = [label.strip() for label in arguments(raw, "label") if label.strip().startswith(prefix + ":")]
        if len(captions) != 1 or len(names) != 1:
            raise ExportError(f"{source}: {kind} needs exactly one caption and one {prefix}: label")
        label = names[0]
        slug = label[len(prefix) + 1:]
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
            raise ExportError(f"{source}: unsafe or noncanonical label {label!r}")
        if label in labels:
            raise ExportError(f"duplicate export label {label}")
        labels.add(label)
        descendants = [child for child in envs if env.body <= child.start < env.stop]
        children = [child for child in descendants if child.name == child_name]
        if len(children) != 1:
            raise ExportError(f"{source}: expected one {child_name}, found {len(children)}")
        child = children[0]
        def contextual(function, *args):
            try:
                return function(*args)
            except ExportError as error:
                raise ExportError(f"{source} ({label}): {error}") from error
        # Graph contents are an opaque, exact TikZ program. Other float bodies
        # have a narrow grammar so unknown environments cannot disappear.
        if kind != "figure":
            allowed = {child_name, "center", "minipage"} | MATH_ENVS
            unknown = [e.name for e in descendants if e.name not in allowed]
            if unknown:
                raise ExportError(f"{source}: unsupported {kind} environments: {', '.join(unknown)}")
            literal_envs = re.findall(r"\\begin\{([^}]+)\}", mask(raw, verbatim=False))
            if any(name in VERBATIM for name in literal_envs):
                raise ExportError(f"{source}: literal environment inside {kind} cannot be converted")
        converter = Converter()
        shell = (manuscript.text[env.body:child.start]
                 + " " * (child.end - child.start)
                 + manuscript.text[child.end:env.stop])
        contextual(inspect_float_shell, shell, converter)
        caption = contextual(converter.plain, captions[0])
        original = manuscript.original(env.start, env.end)
        if kind == "algorithm":
            converted = contextual(converter.pseudocode, manuscript.text[child.body:child.stop])
            content = (f"# {MARKER}\n# slug: {slug}\n# source: {source}\n# label: {label}\n"
                       f"# pseudocode source: {manuscript.source(child.start)}\n"
                       f"# caption: {caption}\n\n{converted}\n\n# Original LaTeX:\n"
                       + comment_lines(original, "# ") + "\n")
        elif kind == "figure":
            content = (f"% {MARKER}\n% Slug: {slug}\n% Source: {source}\n"
                       f"% TikZ source: {manuscript.source(child.start)}\n% Original label: \\label{{{label}}}\n"
                       "% Original caption (LaTeX source):\n" + comment_lines(captions[0], "%   ")
                       + f"\n% Caption: {caption}\n"
                       "% Setup: support/compiler-pseudocode.sty (TikZ libraries and shared styles).\n"
                       + manuscript.original(child.start, child.end) + "\n\n% Original figure LaTeX:\n"
                       + comment_lines(original, "% ") + "\n")
        else:
            columns, rows = contextual(table_rows, manuscript.text[child.body:child.stop])
            rendered = ["| " + " | ".join(markdown_cell(contextual(converter.plain, cell)) for cell in row) + " |" for row in rows]
            rendered.insert(1, "| " + " | ".join(["---"] * columns) + " |")
            content = (f"<!-- {MARKER} -->\n# {markdown_cell(caption)}\n\n"
                       f"- Source: `{source}`\n- Tabular source: `{manuscript.source(child.start)}`\n"
                       f"- Original label: `{label}`\n\n"
                       + "\n".join(rendered) + "\n\n<!-- Original LaTeX -->\n\n"
                       + fenced(original) + "\n")
        warnings.extend(f"{source} ({label}): {warning}" for warning in sorted(converter.warnings))
        artifacts.append(Artifact(directory, slug + extension, label, source, caption, content))
    if not artifacts:
        raise ExportError("no named floats found in the reachable manuscript")
    return sorted(artifacts, key=lambda item: (item.directory, item.filename)), warnings


def expected_files(artifacts: list[Artifact]) -> dict[Path, str]:
    expected = {}
    for _, directory, extension, _ in KINDS.values():
        items = [item for item in artifacts if item.directory == directory]
        manifest = [f"# {MARKER}", f"# {directory}: {len(items)} artifacts reachable from index.ltx",
                    "# filename\tsource:line\tlabel"]
        readme = [f"<!-- {MARKER} -->", f"# {directory}", "",
                  f"{len(items)} artifacts from the manuscript reachable through `index.ltx`.", "",
                  "Regenerate: `python3 support/export-artifacts.py`.",
                  "Verify: `python3 support/export-artifacts.py --check`.",
                  "See [exporter documentation](../support/export-artifacts.md) for the source contract.", "",
                  "| File | Source | Label | Caption |", "| --- | --- | --- | --- |"]
        for item in items:
            expected[Path(directory) / item.filename] = item.content
            manifest.append(f"{item.filename}\t{item.source}\t{item.label}")
            readme.append("| " + " | ".join(markdown_cell(value) for value in
                                           (item.filename, item.source, item.label, item.caption)) + " |")
        expected[Path(directory) / "MANIFEST.txt"] = "\n".join(manifest) + "\n"
        expected[Path(directory) / "README.md"] = "\n".join(readme) + "\n"
    return expected


def recognized(path: Path, text: str) -> bool:
    """Recognize this generator or the repository's three legacy trace formats."""
    if MARKER in text.split("\n", 1)[0]:
        return True
    if path.name == "MANIFEST.txt":
        if re.match(r"# (?:pseudo-code|graphs-code|tables-code) manifest\b", text):
            return True
        if path.parent.name == "graphs-code":
            return text.startswith("graphs-code manifest: ") and "Generated from:" in text
        if path.parent.name == "pseudo-code":
            return bool(text.strip()) and all(re.fullmatch(r"[a-z0-9-]+\.sudo", line)
                                             for line in text.splitlines())
        return False
    if path.name == "README.md":
        headings = {"# Serialized pseudocode", "# graphs-code — serialized TikZ diagrams", "# Tables Code Index"}
        return text.split("\n", 1)[0] in headings and "|" in text and "label" in text.lower()
    if path.name.endswith(".sudo"):
        return text.startswith("# slug: ") and "# label: alg:" in text and "# Original LaTeX:" in text
    if path.name.endswith(".tikz.tex"):
        return text.startswith("% Slug: ") and "% Original label: \\label{fig:" in text and "\\begin{tikzpicture}" in text
    if path.suffix == ".md":
        return "- Source file: `" in text and "- Original label: `tab:" in text and "<!-- Original LaTeX -->" in text
    return False


def synchronize(output: Path, expected: dict[Path, str], check: bool) -> list[str]:
    """Preflight the complete inventory, then write; never remove unknown files."""
    problems = []
    stale = []
    writes = []
    for relative, content in sorted(expected.items()):
        path = output / relative
        if path.is_symlink() or path.parent.is_symlink():
            problems.append(f"refusing symlink output: {relative}")
            continue
        if path.exists():
            actual = read_exact(path)
            if actual == content:
                continue
            if not recognized(relative, actual):
                problems.append(f"unrecognized file would be overwritten: {relative}")
                continue
            if check:
                problems.append(f"stale: {relative}")
        elif check:
            problems.append(f"missing: {relative}")
        writes.append((path, content))
    for _, directory, extension, _ in KINDS.values():
        folder = output / directory
        if not folder.exists():
            continue
        for path in sorted(folder.rglob("*")):
            if not path.is_file() or path.relative_to(output) in expected:
                continue
            if path.name.endswith(extension) or path.name in {"MANIFEST.txt", "README.md"}:
                relative = path.relative_to(output)
                if path.is_symlink() or not recognized(relative, read_exact(path)):
                    problems.append(f"unrecognized inventory file (preserved): {relative}")
                elif check:
                    problems.append(f"obsolete generated file: {relative}")
                else:
                    stale.append(path)
    if problems or check:
        return problems
    for path, content in writes:
        path.parent.mkdir(parents=True, exist_ok=True)
        # No helper files are left behind; the complete plan was validated first.
        with path.open("w", encoding="utf-8", newline="") as stream:
            stream.write(content)
    for path in stale:
        path.unlink()
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="manuscript root (default: repository containing this script)")
    parser.add_argument("--output-root", type=Path, help="export destination (default: manuscript root)")
    parser.add_argument("--check", action="store_true", help="compare content and inventory without writing")
    parser.add_argument("--strict", action="store_true", help="fail on retained unsupported inline notation")
    args = parser.parse_args(argv)
    try:
        manuscript = Manuscript(args.root)
        artifacts, warnings = collect(manuscript)
        expected = expected_files(artifacts)
        for warning in warnings:
            print("warning: " + warning, file=sys.stderr)
        if args.strict and warnings:
            raise ExportError("strict mode: unsupported inline notation was retained")
        manuscript.verify_unchanged()
        problems = synchronize((args.output_root or args.root).resolve(), expected, args.check)
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            return 1
        counts = ", ".join(f"{sum(a.directory == directory for a in artifacts)} {directory}"
                           for _, directory, _, _ in KINDS.values())
        print(("Verified " if args.check else "Exported ") + counts)
        return 0
    except (ExportError, OSError, UnicodeError) as error:
        print(f"export error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
