class ExportError(ValueError):
    """A source or output cannot safely be serialized."""


def read_exact(path: Path) -> str:
    with path.open(encoding="utf-8", newline="") as stream:
        return stream.read()


def group(text: str, pos: int, opening: str = "{") -> tuple[str, int]:
    """Read a balanced argument, respecting escapes and nested braces."""
    while pos < len(text) and text[pos].isspace():
        pos += 1
    if pos >= len(text) or text[pos] != opening:
        raise ExportError(f"expected {opening!r} near {text[pos:pos + 60]!r}")
    start = pos + 1
    stack = ["}" if opening == "{" else "]"]
    pos += 1
    while pos < len(text):
        if text[pos] == "\\":
            match = COMMAND.match(text, pos)
            if match and match[1] in {"verb", "verb*"}:
                delimiter = text[match.end():match.end() + 1]
                close = text.find(delimiter, match.end() + 1) if delimiter else -1
                if close < 0:
                    raise ExportError("unclosed inline verbatim argument")
                pos = close + 1
            else:
                pos = match.end() if match else pos + 1
            continue
        char = text[pos]
        if char == "{" or (char == "[" and stack[-1] == "]"):
            stack.append("}" if char == "{" else "]")
        elif char == stack[-1]:
            stack.pop()
            if not stack:
                return text[start:pos], pos + 1
        pos += 1
    raise ExportError("unclosed argument")


def optional(text: str, pos: int) -> int:
    while pos < len(text) and text[pos].isspace():
        pos += 1
    return group(text, pos, "[")[1] if text[pos:pos + 1] == "[" else pos


def mask(text: str, verbatim: bool = True) -> str:
    """Blank comments and literal listings without changing source offsets."""
    result = list(text)

    def blank(start: int, end: int) -> None:
        result[start:end] = ["\n" if c == "\n" else " " for c in text[start:end]]

    pos = 0
    while pos < len(text):
        if text[pos] == "%":
            end = text.find("\n", pos)
            end = len(text) if end < 0 else end
            blank(pos, end)
            pos = end
        elif text[pos] == "\\":
            match = COMMAND.match(text, pos)
            if not match:
                pos += 1
                continue
            name = match[1]
            end = match.end()
            if name in {"verb", "verb*"}:
                if end >= len(text) or text[end].isspace():
                    raise ExportError("invalid \\verb delimiter")
                close = text.find(text[end], end + 1)
                if close < 0:
                    raise ExportError("unclosed \\verb")
                if verbatim:
                    blank(pos, close + 1)
                end = close + 1
            elif verbatim and name == "begin":
                env, body = group(text, end)
                if env in VERBATIM:
                    close = text.find("\\end{" + env + "}", body)
                    if close < 0:
                        raise ExportError(f"unclosed literal environment {env}")
                    end = close + len("\\end{" + env + "}")
                    blank(pos, end)
            pos = end
        else:
            pos += 1
    return "".join(result)


def without_comments(text: str) -> str:
    """Remove comments and their newlines for TeX's word-joining semantics."""
    clean = mask(text, verbatim=False)
    pieces = []
    last = 0
    pos = 0
    while pos < len(text):
        if text[pos] == "%" and clean[pos] != "%":
            pieces.append(text[last:pos])
            newline = text.find("\n", pos)
            pos = len(text) if newline < 0 else newline + 1
            last = pos
        else:
            pos += 1
    pieces.append(text[last:])
    return "".join(pieces)


@dataclass
class Segment:
    start: int
    end: int
    path: Path
    offset: int


class Manuscript:
    def __init__(self, root: Path, master: str = "index.ltx"):
        self.root = root.resolve()
        self.sources: dict[Path, str] = {}
        self.segments: list[Segment] = []
        self.parts: list[str] = []
        self.length = 0
        self._expand(self.root / master, [])
        self.text = "".join(self.parts)
        self.starts = [s.start for s in self.segments]

    def _append(self, path: Path, start: int, end: int) -> None:
        if start == end:
            return
        self.parts.append(self.sources[path][start:end])
        self.segments.append(Segment(self.length, self.length + end - start, path, start))
        self.length += end - start

    def _expand(self, path: Path, stack: list[Path]) -> None:
        path = path.resolve()
        if not path.is_relative_to(self.root):
            raise ExportError(f"input outside manuscript root: {path}")
        relative = path.relative_to(self.root)
        if any(part in {"sources", "book", "pseudo-code", "graphs-code", "tables-code"}
               for part in relative.parts):
            raise ExportError(f"excluded input tree: {relative}")
        if path in stack:
            raise ExportError("input cycle: " + " -> ".join(str(p) for p in stack + [path]))
        if path not in self.sources:
            self.sources[path] = read_exact(path)
        text = self.sources[path]
        clean = mask(text)
        last = 0
        consumed = 0
        for match in COMMAND.finditer(clean):
            if match.start() < consumed:
                continue
            if match[1] == "endinput":
                self._append(path, last, match.start())
                return
            if match[1] not in {"input", "include"}:
                continue
            filename, end = group(clean, match.end())
            filename = filename.strip()
            if not re.fullmatch(r"[A-Za-z0-9_./ -]+", filename):
                raise ExportError(f"nonliteral input path in {relative}: {filename!r}")
            target = Path(filename)
            if not target.suffix:
                target = target.with_suffix(".tex")
            # TeX's build-root interpretation takes precedence; local fragments
            # are also accepted when there is no build-root file of that name.
            candidates = [self.root / target, path.parent / target]
            child = next((p for p in candidates if p.is_file()), candidates[0])
            self._append(path, last, match.start())
            self._expand(child, stack + [path])
            last = consumed = end
        self._append(path, last, len(text))

    def location(self, offset: int) -> tuple[Path, int]:
        segment = self.segments[bisect_right(self.starts, offset) - 1]
        return segment.path, segment.offset + offset - segment.start

    def source(self, offset: int) -> str:
        path, position = self.location(offset)
        return f"{path.relative_to(self.root).as_posix()}:{self.sources[path].count(chr(10), 0, position) + 1}"

    def original(self, start: int, end: int) -> str:
        """Keep input directives in traces when a float lives in one file."""
        first, a = self.location(start)
        last, b = self.location(end - 1)
        if first == last and a <= b:
            return self.sources[first][a:b + 1]
        raise ExportError(f"environment crosses input file boundaries at {self.source(start)}")

    def verify_unchanged(self) -> None:
        for path, original in self.sources.items():
            if read_exact(path) != original:
                raise ExportError(f"source changed during export; retry after edits finish: {path}")


@dataclass
class Environment:
    name: str
    start: int
    body: int
    stop: int = 0
    end: int = 0
    parent: Environment | None = None


def environments(text: str) -> list[Environment]:
    clean = mask(text)
    stack: list[Environment] = []
    found: list[Environment] = []
    for match in COMMAND.finditer(clean):
        if match[1] not in {"begin", "end"}:
            continue
        name, end = group(clean, match.end())
        if match[1] == "begin":
            env = Environment(name, match.start(), end, parent=stack[-1] if stack else None)
            found.append(env)
            stack.append(env)
        else:
            if not stack or stack[-1].name != name:
                raise ExportError(f"mismatched environment end: {name}")
            env = stack.pop()
            env.stop, env.end = match.start(), end
    if stack:
        raise ExportError(f"unclosed environment: {stack[-1].name}")
    return found


def arguments(text: str, command: str) -> list[str]:
    clean = mask(text)
    values = []
    consumed = 0
    for match in COMMAND.finditer(clean):
        if match.start() < consumed or match[1] != command:
            continue
        start = optional(clean, match.end())
        _, consumed = group(clean, start)
        # The balanced parse uses the masked view; return the original bytes.
        values.append(text[start + 1:consumed - 1])
    return values


